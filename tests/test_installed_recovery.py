def test_installed_verification_is_read_only_and_scoped(installed):
    module, root, expected, config_sha, outputs, calls = installed
    before = {str(p): p.read_bytes() for p in root.rglob('*') if p.is_file()}
    result = module.verify(expected, config_sha)
    assert result['status'] == 'PASS'
    assert result['guest_writes'] is False
    assert result['grub_matches_image_assembly'] is True
    assert result['digest'] == expected
    assert before == {str(p): p.read_bytes() for p in root.rglob('*') if p.is_file()}
    assert set(calls) == set(outputs)


@pytest.mark.parametrize('name', ['boot/grub2/grub.cfg', 'etc/greenboot/greenboot.conf',
                                'usr/share/apex/greenboot.conf'])
def test_installed_verification_rejects_changed_configuration(installed, name):
    module, root, expected, config_sha, _, _ = installed
    path = root / name
    path.write_bytes(path.read_bytes() + b'changed\n')
    with pytest.raises(ValueError):
        module.verify(expected, config_sha)


def test_matching_but_broken_grub_is_rejected(installed):
    module, root, expected, config_sha, _, _ = installed
    fragment = b'save_env boot_success'
    (root / 'usr/lib/bootupd/grub2-static/configs.d/08_greenboot.cfg').write_bytes(fragment)
    (root / 'boot/grub2/grub.cfg').write_bytes(module.assemble(b'pre\n', {'08_greenboot.cfg': fragment}))
    with pytest.raises(ValueError, match='separator'):
        module.verify(expected, config_sha)


@pytest.mark.parametrize('command,value', [(('systemd-detect-virt', '--vm'), 'none\n'),
                                          (('getenforce',), 'Permissive\n')])
def test_installed_verification_rejects_wrong_environment(installed, command, value):
    module, _, expected, config_sha, outputs, _ = installed
    outputs[command] = value
    with pytest.raises(ValueError):
        module.verify(expected, config_sha)


def test_installed_verification_rejects_wrong_digest(installed):
    module, _, _, config_sha, _, _ = installed
    with pytest.raises(ValueError, match='digest'):
        module.verify('sha256:' + 'b' * 64, config_sha)
