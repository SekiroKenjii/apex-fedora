import importlib.util
import hashlib
import json
from pathlib import Path

import pytest


def probe_module():
    spec = importlib.util.spec_from_file_location('probe', Path(__file__).resolve().parents[1] / 'guest/installed-recovery-probe.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_probe_assembles_ordered_static_fragments_without_fixing_them():
    module = probe_module()
    result = module.assemble(b'pre\n', {'08.cfg': b'no-newline', '01.cfg': b'first\n', 'README': b'ignored'})
    assert result == (b'# Generated by bootupd / do not edit\n\npre\n'
                      b'\n### BEGIN 01.cfg ###\nfirst\n### END 01.cfg ###\n'
                      b'\n### BEGIN 08.cfg ###\nno-newline### END 08.cfg ###\n')
    assert b'ignored' not in result


